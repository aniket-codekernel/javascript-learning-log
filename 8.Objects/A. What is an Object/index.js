//A. What is an Object
// An object stores related data together as key: value pairs.
/*
 * An array is a numbered list (0, 1, 2...).
 * An object is a labeled box. Every item has a name (key).
*/
const person ={
    name:"Aniket",  //key:name value:Aniket  
    age:20,        //key:age value:20
    isstudent:true //key:isstudent value:true
};
//Use an array when order matters (a list of marks). Use an object when you describe one thing with many details (a person, a car, a product).

