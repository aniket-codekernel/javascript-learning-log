//U. Object vs Array
/*
================================================================================================================
                                         Array vs Object
================================================================================================================

|           | Array                  | Object                                                           |
|-----------|------------------------|------------------------------------------------------------------|
| Access by | Index (0, 1, 2)        | Key (name)                                                       |
| Order     | Matters                | Keys keep insertion order (integer-like keys come first, sorted) |
| Best for  | Lists of similar items | One thing with many details                                      |
| Loop with | for...of, forEach      | Object.entries(), for...in                                       |
| typeof    | "object"               | "object"                                                         |

================================================================================================================
*/